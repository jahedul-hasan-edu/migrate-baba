//! Migration plan generation: turn `current` (target) into `desired`, emitting an ordered,
//! dependency-aware list of SQL steps annotated with hazards.

use std::cmp::Reverse;
use std::collections::{BTreeMap, BTreeSet};

use serde::{Deserialize, Serialize};

use crate::ddl;
use crate::diff::{ObjectKey, ObjectKind};
use crate::ident::{quote_ident, quote_literal};
use crate::model::*;

/// Execution phases, in order.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub enum Phase {
    Schemas,
    Extensions,
    Types,
    Sequences,
    DropDependants,
    DropFunctions,
    Tables,
    Functions,
    ConstraintsIndexes,
    ForeignKeys,
    Views,
    LateFunctions,
    TriggersPolicies,
    SequenceOwnership,
    Drops,
    Comments,
}

impl Phase {
    pub fn label(self) -> &'static str {
        match self {
            Phase::Schemas => "Create schemas",
            Phase::Extensions => "Extensions",
            Phase::Types => "Types",
            Phase::Sequences => "Sequences",
            Phase::DropDependants => "Drop dependent objects",
            Phase::DropFunctions => "Drop functions",
            Phase::Tables => "Tables & columns",
            Phase::Functions => "Functions & procedures",
            Phase::ConstraintsIndexes => "Constraints & indexes",
            Phase::ForeignKeys => "Foreign keys",
            Phase::Views => "Views",
            Phase::LateFunctions => "Functions depending on views",
            Phase::TriggersPolicies => "Triggers, RLS & policies",
            Phase::SequenceOwnership => "Sequence ownership",
            Phase::Drops => "Drop removed objects",
            Phase::Comments => "Comments",
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub enum Hazard {
    /// Data is deleted (drop table/column…).
    DataLoss,
    /// Table rewrite (long lock on big tables).
    TableRewrite,
    /// Might fail depending on existing data (NOT NULL, new constraints, casts).
    MayFail,
    /// Takes an ACCESS EXCLUSIVE / SHARE lock for a potentially long time.
    LocksTable,
    /// Cannot be generated automatically; statement is commented out.
    Manual,
}

impl Hazard {
    pub fn label(self) -> &'static str {
        match self {
            Hazard::DataLoss => "DATA LOSS",
            Hazard::TableRewrite => "REWRITE",
            Hazard::MayFail => "MAY FAIL",
            Hazard::LocksTable => "LOCKS",
            Hazard::Manual => "MANUAL",
        }
    }

    pub fn explain(self) -> &'static str {
        match self {
            Hazard::DataLoss => "Permanently deletes data",
            Hazard::TableRewrite => "Rewrites the whole table; slow and locks it on large tables",
            Hazard::MayFail => "May fail depending on existing data",
            Hazard::LocksTable => "Locks the table while it runs",
            Hazard::Manual => "Needs a manual migration; left commented out",
        }
    }
}

/// When a step runs relative to the main deployment transaction.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum RunMode {
    InTransaction,
    /// Autocommit before the transaction (e.g. `ALTER TYPE … ADD VALUE`, so later steps can use it).
    BeforeTransaction,
    /// Autocommit after the transaction (e.g. `CREATE INDEX CONCURRENTLY`).
    AfterTransaction,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Step {
    pub phase: Phase,
    #[serde(skip)]
    sub: u8,
    pub object: String,
    pub sql: String,
    pub hazards: Vec<Hazard>,
    pub run: RunMode,
}

impl Step {
    pub fn is_manual(&self) -> bool {
        self.hazards.contains(&Hazard::Manual)
    }
}

#[derive(Clone, Debug, Default, Serialize, Deserialize)]
pub struct Plan {
    pub steps: Vec<Step>,
}

#[derive(Clone, Debug, Default, Serialize, Deserialize)]
pub struct PlanOptions {
    /// Append CASCADE to DROP statements.
    pub cascade_drops: bool,
    /// Build new indexes on existing tables with CONCURRENTLY (outside the transaction).
    pub concurrent_indexes: bool,
}

impl Plan {
    pub fn is_empty(&self) -> bool {
        self.steps.is_empty()
    }

    pub fn hazard_counts(&self) -> BTreeMap<Hazard, usize> {
        let mut m = BTreeMap::new();
        for s in &self.steps {
            for h in &s.hazards {
                *m.entry(*h).or_insert(0) += 1;
            }
        }
        m
    }

    pub fn has_data_loss(&self) -> bool {
        self.steps.iter().any(|s| s.hazards.contains(&Hazard::DataLoss))
    }

    /// Render the plan as a reviewable SQL script.
    pub fn to_sql(&self, title: &str) -> String {
        let mut out = String::new();
        out.push_str(&format!("-- {title}\n-- Generated by Migrate Baba\n"));
        if self.steps.is_empty() {
            out.push_str("-- No differences: nothing to do.\n");
            return out;
        }
        let counts = self.hazard_counts();
        if !counts.is_empty() {
            out.push_str("-- Hazards: ");
            out.push_str(
                &counts.iter().map(|(h, n)| format!("{} x{n}", h.label())).collect::<Vec<_>>().join(", "),
            );
            out.push('\n');
        }
        out.push_str("\nSET check_function_bodies = off;\n");
        let mut phase = None;
        for s in &self.steps {
            if phase != Some(s.phase) {
                phase = Some(s.phase);
                out.push_str(&format!("\n-- ==== {} ====\n", s.phase.label()));
            }
            if !s.hazards.is_empty() {
                out.push_str(&format!(
                    "-- [{}] {}\n",
                    s.hazards.iter().map(|h| h.label()).collect::<Vec<_>>().join(", "),
                    s.object
                ));
            }
            match s.run {
                RunMode::BeforeTransaction => out.push_str("-- (runs outside the transaction, before it)\n"),
                RunMode::AfterTransaction => out.push_str("-- (runs outside the transaction, after it)\n"),
                RunMode::InTransaction => {}
            }
            out.push_str(&s.sql);
            out.push('\n');
        }
        out
    }
}

struct Builder {
    steps: Vec<Step>,
    opts: PlanOptions,
}

impl Builder {
    fn push(&mut self, phase: Phase, sub: u8, object: impl Into<String>, sql: impl Into<String>, hazards: &[Hazard]) {
        self.push_mode(phase, sub, object, sql, hazards, RunMode::InTransaction);
    }

    fn push_mode(
        &mut self,
        phase: Phase,
        sub: u8,
        object: impl Into<String>,
        sql: impl Into<String>,
        hazards: &[Hazard],
        run: RunMode,
    ) {
        self.steps.push(Step { phase, sub, object: object.into(), sql: sql.into(), hazards: hazards.to_vec(), run });
    }

    fn manual(&mut self, phase: Phase, object: impl Into<String>, reason: &str, suggestion: &str) {
        let mut sql = format!("-- MANUAL: {reason}");
        for line in suggestion.lines() {
            sql.push_str(&format!("\n-- {line}"));
        }
        self.push(phase, 9, object, sql, &[Hazard::Manual]);
    }

    fn cascade(&self) -> &'static str {
        if self.opts.cascade_drops {
            " CASCADE"
        } else {
            ""
        }
    }

    fn finish(mut self) -> Plan {
        // Stable: keeps emission order within (phase, sub).
        self.steps.sort_by_key(|s| (s.phase, s.sub));
        Plan { steps: self.steps }
    }
}

/// Generate the steps that turn `current` into `desired`.
pub fn plan(current: &Catalog, desired: &Catalog, opts: &PlanOptions) -> Plan {
    let mut b = Builder { steps: Vec::new(), opts: opts.clone() };
    plan_schemas(&mut b, current, desired);
    plan_extensions(&mut b, current, desired);
    plan_types(&mut b, current, desired);
    plan_sequences(&mut b, current, desired);
    let affected = plan_tables(&mut b, current, desired);
    plan_views(&mut b, current, desired, &affected);
    plan_functions(&mut b, current, desired);
    b.finish()
}

/// Build the desired catalog for a selection: target, with each selected object replaced by its
/// source version (or removed when it doesn't exist in the source).
pub fn build_desired(source: &Catalog, target: &Catalog, selection: &BTreeSet<ObjectKey>) -> Catalog {
    fn set<K: Ord, V: Clone>(m: &mut BTreeMap<K, V>, k: K, v: Option<&V>) {
        match v {
            Some(v) => {
                m.insert(k, v.clone());
            }
            None => {
                m.remove(&k);
            }
        }
    }
    let mut d = target.clone();
    for k in selection {
        match k.kind {
            ObjectKind::Schema => set(&mut d.schemas, k.name.clone(), source.schemas.get(&k.name)),
            ObjectKind::Extension => set(&mut d.extensions, k.name.clone(), source.extensions.get(&k.name)),
            ObjectKind::Type => set(&mut d.types, k.qname(), source.types.get(&k.qname())),
            ObjectKind::Sequence => set(&mut d.sequences, k.qname(), source.sequences.get(&k.qname())),
            ObjectKind::Table => set(&mut d.tables, k.qname(), source.tables.get(&k.qname())),
            ObjectKind::View | ObjectKind::MaterializedView => {
                set(&mut d.views, k.qname(), source.views.get(&k.qname()))
            }
            ObjectKind::Function | ObjectKind::Procedure => {
                let fk = k.function_key();
                set(&mut d.functions, fk.clone(), source.functions.get(&fk))
            }
        }
    }
    d
}

/// Convenience: plan for a selection of diff objects.
pub fn plan_selection(
    source: &Catalog,
    target: &Catalog,
    selection: &BTreeSet<ObjectKey>,
    opts: &PlanOptions,
) -> Plan {
    let desired = build_desired(source, target, selection);
    plan(target, &desired, opts)
}

