fn plan_schemas(b: &mut Builder, cur: &Catalog, des: &Catalog) {
    for (name, s) in &des.schemas {
        match cur.schemas.get(name) {
            None => {
                b.push(Phase::Schemas, 0, format!("schema {name}"), format!("CREATE SCHEMA IF NOT EXISTS {};", quote_ident(name)), &[]);
                if let Some(c) = &s.comment {
                    b.push(Phase::Comments, 0, format!("schema {name}"), ddl::comment_on(&format!("SCHEMA {}", quote_ident(name)), Some(c)), &[]);
                }
            }
            Some(c) if c.comment != s.comment => {
                b.push(Phase::Comments, 0, format!("schema {name}"), ddl::comment_on(&format!("SCHEMA {}", quote_ident(name)), s.comment.as_deref()), &[]);
            }
            _ => {}
        }
    }
    for name in cur.schemas.keys() {
        if !des.schemas.contains_key(name) {
            let sql = format!("DROP SCHEMA IF EXISTS {}{};", quote_ident(name), b.cascade());
            b.push(Phase::Drops, 6, format!("schema {name}"), sql, &[Hazard::DataLoss]);
        }
    }
}

fn plan_extensions(b: &mut Builder, cur: &Catalog, des: &Catalog) {
    for (name, e) in &des.extensions {
        match cur.extensions.get(name) {
            None => {
                let mut sql = String::new();
                if !des.schemas.contains_key(&e.schema) && e.schema != "public" && e.schema != "pg_catalog" {
                    sql.push_str(&format!("CREATE SCHEMA IF NOT EXISTS {};\n", quote_ident(&e.schema)));
                }
                sql.push_str(&format!(
                    "CREATE EXTENSION IF NOT EXISTS {} WITH SCHEMA {};",
                    quote_ident(name),
                    quote_ident(&e.schema)
                ));
                b.push(Phase::Extensions, 0, format!("extension {name}"), sql, &[]);
            }
            Some(c) => {
                if c.schema != e.schema {
                    b.push(Phase::Extensions, 1, format!("extension {name}"), format!("ALTER EXTENSION {} SET SCHEMA {};", quote_ident(name), quote_ident(&e.schema)), &[Hazard::MayFail]);
                }
                if c.version != e.version {
                    b.push(Phase::Extensions, 1, format!("extension {name}"), format!("ALTER EXTENSION {} UPDATE TO {};", quote_ident(name), quote_literal(&e.version)), &[Hazard::MayFail]);
                }
            }
        }
    }
    for name in cur.extensions.keys() {
        if !des.extensions.contains_key(name) {
            let sql = format!("DROP EXTENSION IF EXISTS {}{};", quote_ident(name), b.cascade());
            b.push(Phase::Drops, 5, format!("extension {name}"), sql, &[Hazard::DataLoss]);
        }
    }
}

fn type_sub(t: &TypeDef) -> u8 {
    match t.kind {
        TypeKind::Enum { .. } => 0,
        TypeKind::Domain { .. } => 1,
        TypeKind::Composite { .. } => 2,
    }
}

fn type_keyword(t: &TypeDef) -> &'static str {
    if matches!(t.kind, TypeKind::Domain { .. }) {
        "DOMAIN"
    } else {
        "TYPE"
    }
}

fn plan_types(b: &mut Builder, cur: &Catalog, des: &Catalog) {
    for (name, d) in &des.types {
        let obj = format!("type {name}");
        let Some(c) = cur.types.get(name) else {
            let mut sql = ddl::create_type(&TypeDef { comment: None, ..d.clone() });
            if let Some(cm) = &d.comment {
                b.push(Phase::Comments, 0, obj.clone(), ddl::comment_on(&format!("{} {}", type_keyword(d), name.sql()), Some(cm)), &[]);
            }
            sql = sql.trim().to_string();
            b.push(Phase::Types, type_sub(d), obj, sql, &[]);
            continue;
        };
        if c.comment != d.comment {
            b.push(Phase::Comments, 0, obj.clone(), ddl::comment_on(&format!("{} {}", type_keyword(d), name.sql()), d.comment.as_deref()), &[]);
        }
        match (&c.kind, &d.kind) {
            (TypeKind::Enum { labels: cl }, TypeKind::Enum { labels: dl }) if cl != dl => {
                // Existing labels must appear in the same relative order in the desired list.
                let kept: Vec<&String> = dl.iter().filter(|l| cl.contains(l)).collect();
                let compatible = kept.len() == cl.len() && kept.iter().zip(cl.iter()).all(|(a, b)| *a == b);
                if !compatible {
                    b.manual(
                        Phase::Types,
                        obj,
                        &format!("enum {name} had values removed or reordered"),
                        &format!(
                            "Recreate it: ALTER TYPE {n} RENAME TO {o}; CREATE TYPE {n} AS ENUM ({labels});\n\
                             ALTER TABLE … ALTER COLUMN … TYPE {n} USING col::text::{n}; DROP TYPE {o};",
                            n = name.sql(),
                            o = quote_ident(&format!("{}_old", name.name)),
                            labels = dl.iter().map(|l| quote_literal(l)).collect::<Vec<_>>().join(", ")
                        ),
                    );
                } else {
                    for (i, l) in dl.iter().enumerate() {
                        if cl.contains(l) {
                            continue;
                        }
                        let pos = if i > 0 {
                            format!(" AFTER {}", quote_literal(&dl[i - 1]))
                        } else if let Some(first) = kept.first() {
                            format!(" BEFORE {}", quote_literal(first))
                        } else {
                            String::new()
                        };
                        b.push_mode(
                            Phase::Types,
                            0,
                            obj.clone(),
                            format!("ALTER TYPE {} ADD VALUE IF NOT EXISTS {}{};", name.sql(), quote_literal(l), pos),
                            &[],
                            RunMode::BeforeTransaction,
                        );
                    }
                }
            }
            (
                TypeKind::Domain { base: cb, not_null: cn, default: cdef, checks: cc },
                TypeKind::Domain { base: db, not_null: dn, default: ddef, checks: dc },
            ) => {
                if cb != db {
                    b.manual(Phase::Types, obj.clone(), &format!("base type of domain {name} changed from {cb} to {db}"), "Create a new domain, migrate columns to it, drop the old one.");
                }
                if cdef != ddef {
                    let sql = match ddef {
                        Some(x) => format!("ALTER DOMAIN {} SET DEFAULT {};", name.sql(), x),
                        None => format!("ALTER DOMAIN {} DROP DEFAULT;", name.sql()),
                    };
                    b.push(Phase::Types, 1, obj.clone(), sql, &[]);
                }
                if cn != dn {
                    let sql = format!("ALTER DOMAIN {} {} NOT NULL;", name.sql(), if *dn { "SET" } else { "DROP" });
                    b.push(Phase::Types, 1, obj.clone(), sql, if *dn { &[Hazard::MayFail] } else { &[] });
                }
                for (n, def) in cc {
                    if !dc.iter().any(|(dn2, ddef2)| dn2 == n && ddef2 == def) {
                        b.push(Phase::Types, 1, obj.clone(), format!("ALTER DOMAIN {} DROP CONSTRAINT {};", name.sql(), quote_ident(n)), &[]);
                    }
                }
                for (n, def) in dc {
                    if !cc.iter().any(|(cn2, cdef2)| cn2 == n && cdef2 == def) {
                        b.push(Phase::Types, 1, obj.clone(), format!("ALTER DOMAIN {} ADD CONSTRAINT {} {};", name.sql(), quote_ident(n), def), &[Hazard::MayFail]);
                    }
                }
            }
            (TypeKind::Composite { attrs: ca }, TypeKind::Composite { attrs: da }) if ca != da => {
                let mut actions = Vec::new();
                for (n, _) in ca {
                    if !da.iter().any(|(x, _)| x == n) {
                        actions.push(format!("DROP ATTRIBUTE {}", quote_ident(n)));
                    }
                }
                for (n, ty) in da {
                    match ca.iter().find(|(x, _)| x == n) {
                        None => actions.push(format!("ADD ATTRIBUTE {} {}", quote_ident(n), ty)),
                        Some((_, cty)) if cty != ty => actions.push(format!("ALTER ATTRIBUTE {} TYPE {}", quote_ident(n), ty)),
                        _ => {}
                    }
                }
                if !actions.is_empty() {
                    b.push(Phase::Types, 2, obj, format!("ALTER TYPE {} {};", name.sql(), actions.join(", ")), &[Hazard::MayFail]);
                }
            }
            (TypeKind::Enum { .. }, TypeKind::Enum { .. })
            | (TypeKind::Composite { .. }, TypeKind::Composite { .. }) => {}
            _ => b.manual(Phase::Types, obj, &format!("type {name} changed kind (enum/domain/composite)"), "Drop and recreate the type and every column using it."),
        }
    }
    for (name, c) in &cur.types {
        if !des.types.contains_key(name) {
            let sql = format!("DROP {} IF EXISTS {}{};", type_keyword(c), name.sql(), b.cascade());
            // composite → domain → enum (reverse of creation)
            let sub = 4 - type_sub(c);
            b.push(Phase::Drops, sub, format!("type {name}"), sql, &[Hazard::MayFail]);
        }
    }
}

fn plan_sequences(b: &mut Builder, cur: &Catalog, des: &Catalog) {
    for (name, d) in &des.sequences {
        let obj = format!("sequence {name}");
        match cur.sequences.get(name) {
            None => {
                b.push(Phase::Sequences, 0, obj.clone(), ddl::create_sequence(d), &[]);
                if let Some(o) = &d.owned_by {
                    b.push(Phase::SequenceOwnership, 0, obj, format!("ALTER SEQUENCE {} OWNED BY {};", name.sql(), o), &[]);
                }
            }
            Some(c) => {
                if ddl::sequence_options(c) != ddl::sequence_options(d) {
                    b.push(Phase::Sequences, 0, obj.clone(), format!("ALTER SEQUENCE {} {};", name.sql(), ddl::sequence_options(d)), &[Hazard::MayFail]);
                }
                if c.owned_by != d.owned_by {
                    let o = d.owned_by.clone().unwrap_or_else(|| "NONE".into());
                    b.push(Phase::SequenceOwnership, 0, obj, format!("ALTER SEQUENCE {} OWNED BY {};", name.sql(), o), &[]);
                }
            }
        }
    }
    for name in cur.sequences.keys() {
        if !des.sequences.contains_key(name) {
            let sql = format!("DROP SEQUENCE IF EXISTS {}{};", name.sql(), b.cascade());
            b.push(Phase::Drops, 1, format!("sequence {name}"), sql, &[Hazard::DataLoss]);
        }
    }
}

fn partition_depth(cat: &Catalog, t: &TableDef) -> usize {
    let mut depth = 0;
    let mut p = t.partition_of.clone();
    while let Some(parent) = p {
        depth += 1;
        if depth > 32 {
            break;
        }
        p = cat.tables.get(&parent).and_then(|x| x.partition_of.clone());
    }
    depth
}

fn create_table_steps(b: &mut Builder, t: &TableDef) {
    let obj = format!("table {}", t.name);
    b.push(Phase::Tables, 0, obj.clone(), ddl::create_table_core(t), &[]);
    for c in t.constraints.values().filter(|c| c.kind == ConstraintKind::ForeignKey) {
        b.push(Phase::ForeignKeys, 0, obj.clone(), ddl::add_constraint(&t.name, c), &[]);
    }
    for i in t.indexes.values() {
        b.push(Phase::ConstraintsIndexes, 1, obj.clone(), format!("{};", i.definition), &[]);
    }
    for s in ddl::rls_sql(t) {
        b.push(Phase::TriggersPolicies, 0, obj.clone(), s, &[]);
    }
    for p in t.policies.values() {
        b.push(Phase::TriggersPolicies, 1, obj.clone(), ddl::create_policy(&t.name, p), &[]);
    }
    for tr in t.triggers.values() {
        b.push(Phase::TriggersPolicies, 2, obj.clone(), format!("{};", tr.definition), &[]);
        if let Some(e) = ddl::trigger_enable_sql(&t.name, tr) {
            b.push(Phase::TriggersPolicies, 2, obj.clone(), e, &[]);
        }
    }
    for c in ddl::table_comments(t) {
        b.push(Phase::Comments, 0, obj.clone(), c, &[]);
    }
}

/// Returns the set of tables whose column changes may break dependent views.
fn plan_tables(b: &mut Builder, cur: &Catalog, des: &Catalog) -> BTreeSet<QName> {
    let mut affected = BTreeSet::new();
    let mut key_changed: BTreeSet<QName> = BTreeSet::new();

    let mut added: Vec<&TableDef> = des.tables.values().filter(|t| !cur.tables.contains_key(&t.name)).collect();
    added.sort_by_key(|t| partition_depth(des, t));
    for t in added {
        create_table_steps(b, t);
    }

    let mut removed: Vec<&TableDef> = cur.tables.values().filter(|t| !des.tables.contains_key(&t.name)).collect();
    removed.sort_by_key(|t| Reverse(partition_depth(cur, t)));
    for t in removed {
        let sql = format!("DROP TABLE IF EXISTS {}{};", t.name.sql(), b.cascade());
        b.push(Phase::Drops, 0, format!("table {}", t.name), sql, &[Hazard::DataLoss]);
        affected.insert(t.name.clone());
    }

    for (name, d) in &des.tables {
        if let Some(c) = cur.tables.get(name) {
            alter_table(b, c, d, &mut affected, &mut key_changed);
        }
    }

    // Unchanged FKs that reference a PK/UNIQUE being recreated must be dropped and re-added.
    if !key_changed.is_empty() {
        for (name, d) in &des.tables {
            let Some(c) = cur.tables.get(name) else { continue };
            for fk in d.constraints.values() {
                let refs_changed = fk.kind == ConstraintKind::ForeignKey
                    && fk.ref_table.as_ref().map(|r| key_changed.contains(r)).unwrap_or(false);
                if refs_changed && c.constraints.get(&fk.name) == Some(fk) {
                    let obj = format!("table {name}");
                    b.push(Phase::DropDependants, 3, obj.clone(), ddl::drop_constraint(name, &fk.name), &[]);
                    b.push(Phase::ForeignKeys, 0, obj, ddl::add_constraint(name, fk), &[Hazard::MayFail]);
                }
            }
        }
    }
    affected
}

fn alter_table(
    b: &mut Builder,
    c: &TableDef,
    d: &TableDef,
    affected: &mut BTreeSet<QName>,
    key_changed: &mut BTreeSet<QName>,
) {
    let t = &d.name;
    let tsql = t.sql();
    let obj = format!("table {t}");

    if c.partition_key != d.partition_key || c.partition_of != d.partition_of || c.partition_bound != d.partition_bound {
        b.manual(
            Phase::Tables,
            obj.clone(),
            &format!("partitioning of {t} changed"),
            "Create the new table layout, copy the data (Migrate Data → Append), swap names, drop the old table.",
        );
    }
    if c.unlogged != d.unlogged {
        b.push(
            Phase::Tables,
            1,
            obj.clone(),
            format!("ALTER TABLE {tsql} SET {};", if d.unlogged { "UNLOGGED" } else { "LOGGED" }),
            &[Hazard::TableRewrite, Hazard::LocksTable],
        );
    }

    if d.partition_of.is_none() {
        // Columns
        for dc in &d.columns {
            match c.column(&dc.name) {
                None => {
                    let risky = dc.not_null && dc.default.is_none() && dc.identity.is_none() && dc.generated.is_none();
                    let mut hz = Vec::new();
                    if risky {
                        hz.push(Hazard::MayFail);
                    }
                    if dc.generated.is_some() {
                        hz.push(Hazard::TableRewrite);
                    }
                    b.push(Phase::Tables, 1, obj.clone(), format!("ALTER TABLE {tsql} ADD COLUMN {};", ddl::column_def(dc)), &hz);
                    if let Some(cm) = &dc.comment {
                        b.push(Phase::Comments, 0, obj.clone(), ddl::comment_on(&format!("COLUMN {tsql}.{}", quote_ident(&dc.name)), Some(cm)), &[]);
                    }
                }
                Some(cc) => {
                    if alter_column(b, &obj, &tsql, cc, dc) {
                        affected.insert(t.clone());
                    }
                }
            }
        }
        for cc in &c.columns {
            if d.column(&cc.name).is_none() {
                b.push(
                    Phase::Tables,
                    1,
                    obj.clone(),
                    format!("ALTER TABLE {tsql} DROP COLUMN {}{};", quote_ident(&cc.name), b.cascade()),
                    &[Hazard::DataLoss],
                );
                affected.insert(t.clone());
            }
        }
    }

    // Constraints
    for (n, cc) in &c.constraints {
        if d.constraints.get(n) != Some(cc) {
            let sub = if cc.kind == ConstraintKind::ForeignKey { 3 } else { 4 };
            b.push(Phase::DropDependants, sub, obj.clone(), ddl::drop_constraint(t, n), &[]);
            if matches!(cc.kind, ConstraintKind::PrimaryKey | ConstraintKind::Unique) {
                key_changed.insert(t.clone());
            }
        }
    }
    for (n, dc) in &d.constraints {
        if c.constraints.get(n) != Some(dc) {
            let phase = if dc.kind == ConstraintKind::ForeignKey { Phase::ForeignKeys } else { Phase::ConstraintsIndexes };
            b.push(phase, 0, obj.clone(), ddl::add_constraint(t, dc), &[Hazard::MayFail, Hazard::LocksTable]);
        }
    }

    // Indexes
    for (n, ci) in &c.indexes {
        if d.indexes.get(n) != Some(ci) {
            b.push(Phase::DropDependants, 5, obj.clone(), ddl::drop_index_sql(&t.schema, n), &[]);
        }
    }
    for (n, di) in &d.indexes {
        if c.indexes.get(n) != Some(di) {
            if b.opts.concurrent_indexes && d.partition_key.is_none() {
                let sql = di.definition.replacen(" INDEX ", " INDEX CONCURRENTLY ", 1);
                b.push_mode(Phase::ConstraintsIndexes, 1, obj.clone(), format!("{sql};"), &[], RunMode::AfterTransaction);
            } else {
                b.push(Phase::ConstraintsIndexes, 1, obj.clone(), format!("{};", di.definition), &[Hazard::LocksTable]);
            }
        }
    }

    // Triggers
    for (n, ct) in &c.triggers {
        match d.triggers.get(n) {
            Some(dt) if dt.definition == ct.definition => {}
            _ => b.push(Phase::DropDependants, 1, obj.clone(), format!("DROP TRIGGER IF EXISTS {} ON {tsql};", quote_ident(n)), &[]),
        }
    }
    for (n, dt) in &d.triggers {
        match c.triggers.get(n) {
            Some(ct) if ct.definition == dt.definition => {
                if ct.enabled != dt.enabled {
                    let sql = ddl::trigger_enable_sql(t, dt)
                        .unwrap_or_else(|| format!("ALTER TABLE {tsql} ENABLE TRIGGER {};", quote_ident(n)));
                    b.push(Phase::TriggersPolicies, 2, obj.clone(), sql, &[]);
                }
            }
            _ => {
                b.push(Phase::TriggersPolicies, 2, obj.clone(), format!("{};", dt.definition), &[]);
                if let Some(e) = ddl::trigger_enable_sql(t, dt) {
                    b.push(Phase::TriggersPolicies, 2, obj.clone(), e, &[]);
                }
            }
        }
    }

    // Policies
    for (n, cp) in &c.policies {
        if d.policies.get(n) != Some(cp) {
            b.push(Phase::DropDependants, 2, obj.clone(), format!("DROP POLICY IF EXISTS {} ON {tsql};", quote_ident(n)), &[]);
        }
    }
    for (n, dp) in &d.policies {
        if c.policies.get(n) != Some(dp) {
            b.push(Phase::TriggersPolicies, 1, obj.clone(), ddl::create_policy(t, dp), &[]);
        }
    }

    // RLS flags
    if c.rls_enabled != d.rls_enabled {
        let sql = format!("ALTER TABLE {tsql} {} ROW LEVEL SECURITY;", if d.rls_enabled { "ENABLE" } else { "DISABLE" });
        b.push(Phase::TriggersPolicies, 0, obj.clone(), sql, &[]);
    }
    if c.rls_forced != d.rls_forced {
        let sql = format!("ALTER TABLE {tsql} {} ROW LEVEL SECURITY;", if d.rls_forced { "FORCE" } else { "NO FORCE" });
        b.push(Phase::TriggersPolicies, 0, obj.clone(), sql, &[]);
    }

    if c.comment != d.comment {
        b.push(Phase::Comments, 0, obj, ddl::comment_on(&format!("TABLE {tsql}"), d.comment.as_deref()), &[]);
    }
}

/// Emit column alterations. Returns true if the change can break dependent views.
fn alter_column(b: &mut Builder, obj: &str, tsql: &str, cc: &Column, dc: &Column) -> bool {
    let col = quote_ident(&dc.name);
    let prefix = format!("ALTER TABLE {tsql} ALTER COLUMN {col}");
    let mut breaks_views = false;

    if cc.generated != dc.generated {
        b.push(Phase::Tables, 1, obj, format!("ALTER TABLE {tsql} DROP COLUMN {col};"), &[Hazard::DataLoss]);
        b.push(Phase::Tables, 1, obj, format!("ALTER TABLE {tsql} ADD COLUMN {};", ddl::column_def(dc)), &[Hazard::TableRewrite]);
        return true;
    }

    // What the default is right now, as we go.
    let mut cur_default = if cc.identity.is_some() { None } else { cc.default.clone() };
    let want_default = if dc.identity.is_some() { None } else { dc.default.clone() };

    if cc.data_type != dc.data_type || cc.collation != dc.collation {
        if cur_default.is_some() {
            b.push(Phase::Tables, 1, obj, format!("{prefix} DROP DEFAULT;"), &[]);
            cur_default = None;
        }
        let collate = dc.collation.as_ref().map(|c| format!(" COLLATE {c}")).unwrap_or_default();
        b.push(
            Phase::Tables,
            1,
            obj,
            format!("{prefix} TYPE {}{collate} USING {col}::{};", dc.data_type, dc.data_type),
            &[Hazard::TableRewrite, Hazard::MayFail],
        );
        breaks_views = true;
    }
    if cc.identity.is_some() && dc.identity.is_none() {
        b.push(Phase::Tables, 1, obj, format!("{prefix} DROP IDENTITY IF EXISTS;"), &[]);
    }
    if cur_default != want_default {
        match &want_default {
            Some(x) => b.push(Phase::Tables, 1, obj, format!("{prefix} SET DEFAULT {x};"), &[]),
            None => b.push(Phase::Tables, 1, obj, format!("{prefix} DROP DEFAULT;"), &[]),
        }
    }
    if dc.not_null && !cc.not_null {
        b.push(Phase::Tables, 1, obj, format!("{prefix} SET NOT NULL;"), &[Hazard::MayFail, Hazard::LocksTable]);
    } else if !dc.not_null && cc.not_null {
        b.push(Phase::Tables, 1, obj, format!("{prefix} DROP NOT NULL;"), &[]);
    }
    match (cc.identity, dc.identity) {
        (None, Some(id)) => {
            let kind = if id == Identity::Always { "ALWAYS" } else { "BY DEFAULT" };
            b.push(Phase::Tables, 1, obj, format!("{prefix} ADD GENERATED {kind} AS IDENTITY;"), &[]);
        }
        (Some(a), Some(z)) if a != z => {
            let kind = if z == Identity::Always { "ALWAYS" } else { "BY DEFAULT" };
            b.push(Phase::Tables, 1, obj, format!("{prefix} SET GENERATED {kind};"), &[]);
        }
        _ => {}
    }
    if cc.comment != dc.comment {
        b.push(Phase::Comments, 0, obj, ddl::comment_on(&format!("COLUMN {tsql}.{col}"), dc.comment.as_deref()), &[]);
    }
    breaks_views
}

/// Topological order (dependencies first) of `names`, using `deps` restricted to `names`.
fn topo_order(names: &BTreeSet<QName>, deps: impl Fn(&QName) -> Vec<QName>) -> Vec<QName> {
    fn visit(
        n: &QName,
        names: &BTreeSet<QName>,
        deps: &dyn Fn(&QName) -> Vec<QName>,
        state: &mut BTreeMap<QName, u8>,
        out: &mut Vec<QName>,
    ) {
        match state.get(n) {
            Some(1) | Some(2) => return, // in progress (cycle) or done
            _ => {}
        }
        state.insert(n.clone(), 1);
        for d in deps(n) {
            if names.contains(&d) {
                visit(&d, names, deps, state, out);
            }
        }
        state.insert(n.clone(), 2);
        out.push(n.clone());
    }
    let mut state = BTreeMap::new();
    let mut out = Vec::new();
    for n in names {
        visit(n, names, &deps, &mut state, &mut out);
    }
    out
}

fn plan_views(b: &mut Builder, cur: &Catalog, des: &Catalog, affected_tables: &BTreeSet<QName>) {
    // Reverse dependency graph of the current database.
    let mut dependents: BTreeMap<QName, Vec<QName>> = BTreeMap::new();
    for v in cur.views.values() {
        for d in &v.depends_on {
            dependents.entry(d.clone()).or_default().push(v.name.clone());
        }
    }

    let mut to_drop: BTreeSet<QName> = cur
        .views
        .iter()
        .filter(|(k, v)| des.views.get(*k) != Some(*v))
        .map(|(k, _)| k.clone())
        .collect();
    let mut queue: Vec<QName> = to_drop.iter().cloned().chain(affected_tables.iter().cloned()).collect();
    while let Some(n) = queue.pop() {
        if let Some(ds) = dependents.get(&n) {
            for d in ds {
                if to_drop.insert(d.clone()) {
                    queue.push(d.clone());
                }
            }
        }
    }

    // Drop: dependents before what they depend on → reverse topological order.
    let drop_order = topo_order(&to_drop, |n| cur.views.get(n).map(|v| v.depends_on.clone()).unwrap_or_default());
    for n in drop_order.iter().rev() {
        let v = &cur.views[n];
        let hz: &[Hazard] = if v.materialized && !des.views.contains_key(n) { &[Hazard::DataLoss] } else { &[] };
        let mut sql = ddl::drop_view(v);
        if b.opts.cascade_drops {
            sql = sql.trim_end_matches(';').to_string() + " CASCADE;";
        }
        b.push(Phase::DropDependants, 0, format!("view {n}"), sql, hz);
    }

    // Create: new views + dropped ones that still exist in desired.
    let to_create: BTreeSet<QName> = des
        .views
        .keys()
        .filter(|k| !cur.views.contains_key(*k) || to_drop.contains(*k))
        .cloned()
        .collect();
    for n in topo_order(&to_create, |n| des.views.get(n).map(|v| v.depends_on.clone()).unwrap_or_default()) {
        let v = &des.views[&n];
        b.push(Phase::Views, 0, format!("view {n}"), ddl::create_view(v), &[]);
    }
}

fn plan_functions(b: &mut Builder, cur: &Catalog, des: &Catalog) {
    let view_names: Vec<(String, String)> =
        des.views.keys().map(|v| (v.sql(), v.to_string())).collect();
    let phase_for = |f: &FunctionDef| {
        let sig = format!("{} {}", f.identity_args, f.result.as_deref().unwrap_or(""));
        if view_names.iter().any(|(q, p)| sig.contains(q.as_str()) || sig.contains(p.as_str())) {
            Phase::LateFunctions
        } else {
            Phase::Functions
        }
    };

    for (k, c) in &cur.functions {
        if !des.functions.contains_key(k) {
            let mut sql = ddl::drop_function(c);
            if b.opts.cascade_drops {
                sql = sql.trim_end_matches(';').to_string() + " CASCADE;";
            }
            b.push(Phase::DropFunctions, 0, format!("{} {k}", c.kind_sql().to_lowercase()), sql, &[Hazard::MayFail]);
        }
    }
    for (k, d) in &des.functions {
        let obj = format!("{} {k}", d.kind_sql().to_lowercase());
        let body_sql = || {
            let mut s = d.definition.trim_end().to_string();
            if !s.ends_with(';') {
                s.push(';');
            }
            s
        };
        match cur.functions.get(k) {
            None => {
                b.push(phase_for(d), 0, obj.clone(), body_sql(), &[]);
                if let Some(cm) = &d.comment {
                    b.push(Phase::Comments, 0, obj, ddl::comment_on(&format!("{} {}", d.kind_sql(), d.signature_sql()), Some(cm)), &[]);
                }
            }
            Some(c) => {
                let body_changed = normalize_body(&c.definition) != normalize_body(&d.definition);
                if c.result != d.result || c.kind != d.kind {
                    b.push(Phase::DropFunctions, 0, obj.clone(), ddl::drop_function(c), &[Hazard::MayFail]);
                    b.push(phase_for(d), 0, obj.clone(), body_sql(), &[]);
                } else if body_changed {
                    b.push(phase_for(d), 0, obj.clone(), body_sql(), &[]);
                }
                if c.comment != d.comment {
                    b.push(Phase::Comments, 0, obj, ddl::comment_on(&format!("{} {}", d.kind_sql(), d.signature_sql()), d.comment.as_deref()), &[]);
                }
            }
        }
    }
}
