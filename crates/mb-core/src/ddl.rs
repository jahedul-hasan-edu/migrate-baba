//! DDL rendering for single objects. Used both for migration plans and the side-by-side view.

use crate::ident::{qualified, quote_ident, quote_literal, quote_nullable};
use crate::model::*;

pub fn comment_on(object: &str, comment: Option<&str>) -> String {
    format!("COMMENT ON {object} IS {};", quote_nullable(comment))
}

pub fn create_schema(s: &SchemaDef) -> String {
    let mut out = format!("CREATE SCHEMA IF NOT EXISTS {};", quote_ident(&s.name));
    if let Some(c) = &s.comment {
        out.push('\n');
        out.push_str(&comment_on(&format!("SCHEMA {}", quote_ident(&s.name)), Some(c)));
    }
    out
}

pub fn create_extension(e: &ExtensionDef) -> String {
    format!(
        "CREATE EXTENSION IF NOT EXISTS {} WITH SCHEMA {} VERSION {};",
        quote_ident(&e.name),
        quote_ident(&e.schema),
        quote_literal(&e.version)
    )
}

pub fn create_type(t: &TypeDef) -> String {
    let mut out = match &t.kind {
        TypeKind::Enum { labels } => format!(
            "CREATE TYPE {} AS ENUM ({});",
            t.name.sql(),
            labels.iter().map(|l| quote_literal(l)).collect::<Vec<_>>().join(", ")
        ),
        TypeKind::Domain { base, not_null, default, checks } => {
            let mut s = format!("CREATE DOMAIN {} AS {}", t.name.sql(), base);
            if let Some(d) = default {
                s.push_str(&format!(" DEFAULT {d}"));
            }
            if *not_null {
                s.push_str(" NOT NULL");
            }
            for (name, def) in checks {
                s.push_str(&format!("\n  CONSTRAINT {} {}", quote_ident(name), def));
            }
            s.push(';');
            s
        }
        TypeKind::Composite { attrs } => format!(
            "CREATE TYPE {} AS (\n{}\n);",
            t.name.sql(),
            attrs.iter().map(|(n, ty)| format!("  {} {}", quote_ident(n), ty)).collect::<Vec<_>>().join(",\n")
        ),
    };
    if let Some(c) = &t.comment {
        let kw = if matches!(t.kind, TypeKind::Domain { .. }) { "DOMAIN" } else { "TYPE" };
        out.push('\n');
        out.push_str(&comment_on(&format!("{kw} {}", t.name.sql()), Some(c)));
    }
    out
}

pub fn sequence_options(s: &SequenceDef) -> String {
    format!(
        "AS {} INCREMENT BY {} MINVALUE {} MAXVALUE {} START WITH {} CACHE {}{}",
        s.data_type,
        s.increment,
        s.min,
        s.max,
        s.start,
        s.cache,
        if s.cycle { " CYCLE" } else { " NO CYCLE" }
    )
}

pub fn create_sequence(s: &SequenceDef) -> String {
    format!("CREATE SEQUENCE {} {};", s.name.sql(), sequence_options(s))
}

pub fn column_def(c: &Column) -> String {
    let mut s = format!("{} {}", quote_ident(&c.name), c.data_type);
    if let Some(coll) = &c.collation {
        s.push_str(&format!(" COLLATE {coll}"));
    }
    if let Some(g) = &c.generated {
        s.push_str(&format!(" GENERATED ALWAYS AS ({g}) STORED"));
    } else if let Some(id) = c.identity {
        s.push_str(match id {
            Identity::Always => " GENERATED ALWAYS AS IDENTITY",
            Identity::ByDefault => " GENERATED BY DEFAULT AS IDENTITY",
        });
    } else if let Some(d) = &c.default {
        s.push_str(&format!(" DEFAULT {d}"));
    }
    if c.not_null {
        s.push_str(" NOT NULL");
    }
    s
}

/// `CREATE TABLE` including non-FK constraints inline.
pub fn create_table_core(t: &TableDef) -> String {
    if let (Some(parent), Some(bound)) = (&t.partition_of, &t.partition_bound) {
        let mut s = format!("CREATE TABLE {} PARTITION OF {} {}", t.name.sql(), parent.sql(), bound);
        if let Some(k) = &t.partition_key {
            s.push_str(&format!(" PARTITION BY {k}"));
        }
        s.push(';');
        return s;
    }
    let mut items: Vec<String> = t.columns.iter().map(|c| format!("  {}", column_def(c))).collect();
    for c in t.constraints.values().filter(|c| c.kind != ConstraintKind::ForeignKey) {
        items.push(format!("  CONSTRAINT {} {}", quote_ident(&c.name), c.definition));
    }
    let mut s = format!(
        "CREATE {}TABLE {} (\n{}\n)",
        if t.unlogged { "UNLOGGED " } else { "" },
        t.name.sql(),
        items.join(",\n")
    );
    if let Some(k) = &t.partition_key {
        s.push_str(&format!(" PARTITION BY {k}"));
    }
    s.push(';');
    s
}

pub fn add_constraint(table: &QName, c: &Constraint) -> String {
    format!("ALTER TABLE {} ADD CONSTRAINT {} {};", table.sql(), quote_ident(&c.name), c.definition)
}

pub fn drop_constraint(table: &QName, name: &str) -> String {
    format!("ALTER TABLE {} DROP CONSTRAINT {};", table.sql(), quote_ident(name))
}

pub fn create_policy(table: &QName, p: &Policy) -> String {
    let mut s = format!(
        "CREATE POLICY {} ON {} AS {} FOR {} TO {}",
        quote_ident(&p.name),
        table.sql(),
        if p.permissive { "PERMISSIVE" } else { "RESTRICTIVE" },
        p.cmd,
        if p.roles.is_empty() { "public".to_string() } else { p.roles.join(", ") }
    );
    if let Some(u) = &p.using {
        s.push_str(&format!(" USING ({u})"));
    }
    if let Some(w) = &p.with_check {
        s.push_str(&format!(" WITH CHECK ({w})"));
    }
    s.push(';');
    s
}

pub fn trigger_enable_sql(table: &QName, t: &Trigger) -> Option<String> {
    let action = match t.enabled.as_str() {
        "D" => "DISABLE TRIGGER",
        "R" => "ENABLE REPLICA TRIGGER",
        "A" => "ENABLE ALWAYS TRIGGER",
        _ => return None,
    };
    Some(format!("ALTER TABLE {} {} {};", table.sql(), action, quote_ident(&t.name)))
}

pub fn rls_sql(t: &TableDef) -> Vec<String> {
    let mut out = Vec::new();
    if t.rls_enabled {
        out.push(format!("ALTER TABLE {} ENABLE ROW LEVEL SECURITY;", t.name.sql()));
    }
    if t.rls_forced {
        out.push(format!("ALTER TABLE {} FORCE ROW LEVEL SECURITY;", t.name.sql()));
    }
    out
}

pub fn table_comments(t: &TableDef) -> Vec<String> {
    let mut out = Vec::new();
    if let Some(c) = &t.comment {
        out.push(comment_on(&format!("TABLE {}", t.name.sql()), Some(c)));
    }
    for col in &t.columns {
        if let Some(c) = &col.comment {
            out.push(comment_on(&format!("COLUMN {}.{}", t.name.sql(), quote_ident(&col.name)), Some(c)));
        }
    }
    out
}

/// Complete DDL of a table (for display): table, FKs, indexes, RLS, policies, triggers, comments.
pub fn table_full(t: &TableDef) -> String {
    let mut parts = vec![create_table_core(t)];
    for c in t.constraints.values().filter(|c| c.kind == ConstraintKind::ForeignKey) {
        parts.push(add_constraint(&t.name, c));
    }
    for i in t.indexes.values() {
        parts.push(format!("{};", i.definition));
    }
    parts.extend(rls_sql(t));
    for p in t.policies.values() {
        parts.push(create_policy(&t.name, p));
    }
    for tr in t.triggers.values() {
        parts.push(format!("{};", tr.definition));
        if let Some(e) = trigger_enable_sql(&t.name, tr) {
            parts.push(e);
        }
    }
    parts.extend(table_comments(t));
    parts.join("\n")
}

pub fn create_view(v: &ViewDef) -> String {
    let def = v.definition.trim().trim_end_matches(';');
    let mut s = format!(
        "CREATE {}VIEW {}{} AS\n{};",
        if v.materialized { "MATERIALIZED " } else { "" },
        v.name.sql(),
        v.options.as_ref().map(|o| format!(" WITH ({o})")).unwrap_or_default(),
        def
    );
    for i in v.indexes.values() {
        s.push_str(&format!("\n{};", i.definition));
    }
    if let Some(c) = &v.comment {
        s.push('\n');
        s.push_str(&comment_on(
            &format!("{}VIEW {}", if v.materialized { "MATERIALIZED " } else { "" }, v.name.sql()),
            Some(c),
        ));
    }
    s
}

pub fn drop_view(v: &ViewDef) -> String {
    format!("DROP {}VIEW IF EXISTS {};", if v.materialized { "MATERIALIZED " } else { "" }, v.name.sql())
}

pub fn create_function(f: &FunctionDef) -> String {
    let mut s = f.definition.trim_end().to_string();
    if !s.ends_with(';') {
        s.push(';');
    }
    if let Some(c) = &f.comment {
        s.push('\n');
        s.push_str(&comment_on(&format!("{} {}", f.kind_sql(), f.signature_sql()), Some(c)));
    }
    s
}

pub fn drop_function(f: &FunctionDef) -> String {
    format!("DROP {} IF EXISTS {};", f.kind_sql(), f.signature_sql())
}

pub fn drop_index_sql(schema: &str, name: &str) -> String {
    format!("DROP INDEX IF EXISTS {};", qualified(schema, name))
}
